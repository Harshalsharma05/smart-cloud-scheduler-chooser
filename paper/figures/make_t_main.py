"""W7: main evaluation table (Section 6). Default cell (2 h / 20%): median $/MWh over its 10 events at w_fail 0 and 1;
all 84 feasible events: median over events of the per-event cost ratio to delay-only with the same predictor.
Rows: delay, cap, burst-only, mix (p50), mix (p90), mix-nocloud (p90) with the transformer; mix with last2; delay, mix and
mix-nocloud with the oracle. Reads results/e1/runs.csv and results/e1nc/runs_d*.csv. Writes paper/tables/t_main.tex.
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_numbers as mn  # noqa: E402
from style import ROOT, load_runs  # noqa: E402


def main():
    e1 = load_runs("e1")
    e1 = e1[e1["setting"] != "attribution"]
    nc = mn.read_nc()
    nc["who"] = nc.apply(lambda r: f"nocloud{' p90' if 'cq=p90' in r['setting'] else ''} ({r['predictor']})", axis=1)
    nc["shed_pct"] = 100.0 * nc["shed_mwh"] / (nc["cut"] * nc["base_mean_kw"] * nc["duration_h"] / 1000.0)
    d = pd.concat([e1, nc], ignore_index=True)
    rows = [  # (label, who, delay reference)
        (r"\multicolumn{5}{@{}l}{\emph{Transformer predictor}}", None, None),
        ("delay-only", "delay", "delay"),
        ("cap-only", "cap", "delay"),
        ("burst-only", "burst", "delay"),
        ("mix, p50 bill", "mix", "delay"),
        ("mix, p90 bill", "mix-p90", "delay"),
        ("mix-nocloud, p90", "nocloud p90 (transformer)", "delay"),
        (r"\multicolumn{5}{@{}l}{\emph{Last-two-jobs predictor}}", None, None),
        ("mix", "mix (last2)", "delay (last2)"),
        (r"\multicolumn{5}{@{}l}{\emph{Oracle (upper bound)}}", None, None),
        ("delay-only", "delay+oracle", "delay+oracle"),
        ("mix", "mix+oracle", "delay+oracle"),
        ("mix-nocloud", "nocloud (oracle)", "delay+oracle"),
    ]
    dc = mn.in_cell(d, *mn.DEFAULT)
    out = []
    for label, who, ref in rows:
        if who is None:
            out.append(label + r" \\")
            continue
        s = dc[dc["who"] == who]
        assert len(s) == 10, (who, len(s))
        if s["compliance"].median() < 0.99:
            usd = rf"\multicolumn{{2}}{{c}}{{sheds {s['shed_pct'].median():.0f}\% of target}}"
        else:
            usd = " & ".join(f"{s[c].median():,.0f}".replace(",", "{,}") for c in ("usd_per_mwh", "usd_per_mwh_wfail1"))
        rats = []
        for col in ("cost_usd", "cost_usd_wfail1"):
            if who == ref:
                rats.append("1")
                continue
            a = d[d["who"] == who].set_index("event_id")[col]
            b = d[d["who"] == ref].set_index("event_id")[col]
            r = mn.ratio_stats(a, b)[0]
            rats.append(f"{r:.3f}" if r < 2 else (f"{r:.1f}" if r < 10 else f"{r:.0f}"))
        if who == "cap":
            rats = ["--", "--"]
        out.append(rf"\quad {label} & {usd} & {rats[0]} & {rats[1]} \\")
    tex = "\n".join([
        "% Generated by paper/figures/make_t_main.py from results/e1 and results/e1nc. Do not edit.",
        r"\begin{table}[t]", r"\centering",
        r"\caption{Cost of each policy. Left: median \$/MWh over the 10 events of the default cell (2\,h, 20\%). "
        r"Right: median over the " + str(len(e1["event_id"].unique())) + r" feasible events of the per-event cost ratio to delay-only "
        r"with the same predictor. $w_f$: delay weight of Failed/Killed jobs.}",
        r"\label{tab:main}", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
        r" & \multicolumn{2}{c}{\$/MWh, default cell} & \multicolumn{2}{c}{ratio to delay} \\",
        r"\cmidrule(lr){2-3}\cmidrule(l){4-5}",
        r"Policy & $w_f{=}0$ & $w_f{=}1$ & $w_f{=}0$ & $w_f{=}1$ \\", r"\midrule",
        *out, r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    p = ROOT / "paper" / "tables" / "t_main.tex"
    p.write_text(tex, encoding="utf-8")
    print(tex)
    print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
