"""W9: compact sensitivity table (T4) for the paper. Default cell (2 h / 20%, 10 events), hold rule, transformer, w_f = 0.
Per perturbation: median $/MWh of delay-only and the p90 mix, median per-event ratio mix-p90 / delay-only, events where the mix
is cheaper. The default row comes from results/e1/runs.csv, the perturbations from results/t4/runs_*.csv (S13c).
Writes paper/tables/t4_sens.tex and results/t4/sens_summary.csv.   python paper/figures/make_t4_compact.py
"""
import glob
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_numbers as mn  # noqa: E402
from style import RESULTS, ROOT, load_runs  # noqa: E402

LABEL = {"default": "default", "pessimistic cap curve": "pessimistic cap curve", "host power x0.5": r"host power $\times$0.5",
         "host power x1.5": r"host power $\times$1.5", "p_idle 40 W": r"GPU idle power 40\,W", "PUE 1.3": "PUE 1.3",
         "c_delay x0.5": r"$c_d$ $\times$0.5", "c_delay x2": r"$c_d$ $\times$2", "m=0": "$m=0$", "m=3": "$m=3$",
         "migrate/restore x0.5": r"migrate/restore $\times$0.5", "migrate/restore x2": r"migrate/restore $\times$2"}


def row(name, dl, mx):
    x = pd.concat([mx["cost_usd"].rename("m"), dl["cost_usd"].rename("d")], axis=1).dropna()
    return dict(perturbation=name, delay=dl["usd_per_mwh"].median(), mix_p90=mx["usd_per_mwh"].median(),
                ratio=float((x["m"] / x["d"]).median()), cheaper=int((x["m"] < x["d"] - 1e-9).sum()), events=len(x))


def main():
    e1 = load_runs("e1")
    dc = mn.in_cell(e1[e1["setting"] != "attribution"], *mn.DEFAULT)
    rows = [row("default", dc[dc.who == "delay"].set_index("event_id"), dc[dc.who == "mix-p90"].set_index("event_id"))]
    t = pd.concat([pd.read_csv(f, dtype={"setting": str, "predictor": str}) for f in sorted(glob.glob(str(RESULTS / "t4" / "runs_*.csv")))]).fillna("")
    t = t[(t["predictor"] == "transformer") & (t["feasible"].astype(str) != "False")]
    perts = [p for p in LABEL if p != "default"]
    for p in perts:
        dl = t[(t.policy == "delay") & (t.setting == f"pert={p}")].set_index("event_id")
        mx = t[(t.policy == "mix") & (t.setting == f"pert={p};cq=p90")].set_index("event_id")
        assert len(dl) == len(mx) == 10, (p, len(dl), len(mx))
        rows.append(row(p, dl, mx))
    s = pd.DataFrame(rows)
    s.to_csv(RESULTS / "t4" / "sens_summary.csv", index=False)
    print(s.round(3).to_string(index=False))
    num = lambda v: f"{v:,.0f}".replace(",", "{,}")          # thousands separator on numbers only
    body = [f"{LABEL[r.perturbation]} & {num(r.delay)} & {num(r.mix_p90)} & {r.ratio:.2f} & {r.cheaper} \\\\" for r in s.itertuples()]
    tex = "\n".join([
        "% Generated by paper/figures/make_t4_compact.py from results/e1 and results/t4 (S13c, hold rule). Do not edit.",
        r"\begin{table}[t]", r"\centering",
        r"\caption{Sensitivity in the default cell (10 events, transformer, $w_f=0$): median \$/MWh of delay-only and the p90 mix, "
        r"median per-event ratio of the two, and events in which the mix is cheaper.}",
        r"\label{tab:sens}", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
        r"Perturbation & delay & mix-p90 & ratio & cheaper \\", r"\midrule",
        *body, r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    (ROOT / "paper" / "tables" / "t4_sens.tex").write_text(tex, encoding="utf-8")
    print("wrote paper/tables/t4_sens.tex")


if __name__ == "__main__":
    main()
