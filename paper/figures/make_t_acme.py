"""W11 (step 36): Table of the Acme (Seren) results -> paper/tables/t_acme.tex. Reads results/acme_e1/runs.csv only.

Left: median $/MWh over the 10 events of the default cell (2 h, 20%), w_f = 0 and 1. Right: per-event cost ratio to
delay-only with the same predictor, median over all events (w_f = 0), and the number of events in which the policy is cheaper.
Run from the repo root: python paper/figures/make_t_acme.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "results" / "acme_e1" / "runs.csv"
OUT = ROOT / "paper" / "tables" / "t_acme.tex"


def who(r):
    s = r["setting"]
    if r["policy"] == "cap":
        return "cap"
    if r["policy"] == "mix":
        return ("nocloud" if "nocloud" in s else "mix-p90" if "cq=p90" in s else "mix") + "/" + r["predictor"]
    return f"{r['policy']}/{r['predictor']}"


def num(v, ratio=False):
    if pd.isna(v):
        return "--"
    if ratio:
        return f"{v:.3f}" if v < 2 else f"{v:.1f}"
    return f"{v:,.0f}".replace(",", "{,}")


def main():
    r = pd.read_csv(RUNS, dtype={"selector": str, "predictor": str, "setting": str}).fillna({"predictor": "", "setting": ""})
    r = r[~r["setting"].str.startswith("price=") & (r["feasible"].astype(str) != "False")]
    r["who"] = r.apply(who, axis=1)
    n_ev = r["event_id"].nunique()
    dc = r[(r["duration_h"] == 2) & (r["cut"].sub(0.2).abs() < 1e-9)]
    med = dc.groupby("who")[["usd_per_mwh", "usd_per_mwh_wfail1"]].median()
    p = r.pivot_table(index="event_id", columns="who", values="cost_usd", aggfunc="first")
    cap_ok = int(((r["who"] == "cap") & (r["compliance"] >= 0.99)).sum())

    def row(label, w, pred):
        base = p[f"delay/{pred}"]
        if w.startswith("delay"):
            rat, ch = "1", "--"
        else:
            x = pd.concat([p[w].rename("a"), base.rename("b")], axis=1).dropna()
            rat, ch = num((x["a"] / x["b"]).median(), True), str(int((x["a"] < x["b"] - 1e-9).sum()))
        return f"\\quad {label} & {num(med.loc[w, 'usd_per_mwh'])} & {num(med.loc[w, 'usd_per_mwh_wfail1'])} & {rat} & {ch} \\\\"

    L = [r"\multicolumn{5}{@{}l}{\emph{Transformer predictor}} \\",
         row("delay-only", "delay/transformer", "transformer"),
         f"\\quad cap-only & \\multicolumn{{4}}{{l}}{{complies in {cap_ok} of {n_ev} events}} \\\\",
         row("burst-only", "burst/transformer", "transformer"),
         row("mix, p50 bill", "mix/transformer", "transformer"),
         row("mix, p90 bill", "mix-p90/transformer", "transformer"),
         row("mix-nocloud, p90", "nocloud/transformer", "transformer")]
    for name, pred in (("Gradient-boosted trees", "gbdt"), ("LightGBM", "lightgbm")):
        L += [f"\\multicolumn{{5}}{{@{{}}l}}{{\\emph{{{name}}}}} \\\\", row("delay-only", f"delay/{pred}", pred),
              row("mix, p90 bill", f"mix-p90/{pred}", pred)]
    L += [r"\multicolumn{5}{@{}l}{\emph{Oracle (upper bound)}} \\", row("delay-only", "delay/oracle", "oracle"),
          row("burst-only", "burst/oracle", "oracle"), row("mix", "mix/oracle", "oracle")]
    tex = ("% Generated by paper/figures/make_t_acme.py from results/acme_e1/runs.csv. Do not edit.\n"
           "\\begin{table}[t]\n\\centering\n"
           f"\\caption{{Acme (Seren). Left: median \\$/MWh over the 10 events of the default cell. Right: median over the {n_ev} "
           "events of the per-event cost ratio to delay-only with the same predictor ($w_f=0$), and events in which the policy is cheaper.}\n"
           "\\label{tab:acme}\n\\footnotesize\n\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{@{}lrrrr@{}}\n\\toprule\n"
           " & \\multicolumn{2}{c}{\\$/MWh, default cell} & \\multicolumn{2}{c}{vs.\\ delay, $w_f{=}0$} \\\\\n"
           "\\cmidrule(lr){2-3}\\cmidrule(l){4-5}\n"
           f"Policy & $w_f{{=}}0$ & $w_f{{=}}1$ & ratio & cheaper \\\\\n\\midrule\n" + "\n".join(L) +
           "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    OUT.write_text(tex, encoding="utf-8")
    print(tex)


if __name__ == "__main__":
    main()
